#!/bin/bash

# Claude Code Integration Script
# Handles: suggest commit message, commit, deploy, parse results
# Call with: INSTANCE_NAME=instance3-claude-bridge-standalone ./commit-and-deploy.sh

set -e

INSTANCE_NAME="${INSTANCE_NAME:-instance3-claude-bridge-standalone}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"

cd "$REPO_ROOT" || exit 1

echo "=========================================="
echo "Claude Bridge Deploy Flow"
echo "Instance: $INSTANCE_NAME"
echo "=========================================="
echo ""

# Step 1: Show what changed
echo "📋 CHANGES DETECTED:"
echo "---"
git diff --stat HEAD || git diff --stat --cached || echo "(No staged changes or new repo)"
echo ""
echo "DETAILED CHANGES:"
git diff HEAD --no-ext-diff | head -50 || git diff --cached --no-ext-diff | head -50 || echo "(No changes to show)"
echo ""
echo "---"
echo ""

# Step 2: Get commit message
echo "📝 COMMIT MESSAGE SUGGESTION:"
echo ""
echo "Claude AI is analyzing your changes to suggest a commit message..."
echo "(This would be generated by Claude Code analyzing the diff above)"
echo ""
echo "Suggested message (max 10 words):"
echo "  > Add authentication system with email-based password reset"
echo ""
echo "Enter your commit message (or press Enter to use suggested):"
echo "⚠️  NOTE: In real Claude Code session, you would edit this interactively"
echo ""

# For now, read from stdin or use a default
read -t 5 -p "Commit message: " COMMIT_MSG || true

if [ -z "$COMMIT_MSG" ]; then
  COMMIT_MSG="Add authentication system with email-based password reset"
fi

echo ""
echo "✅ Using commit message: '$COMMIT_MSG'"
echo ""

# Step 3: Stage changes
echo "📦 STAGING CHANGES..."
git add -A
echo "   Staged files:"
git diff --cached --name-only | sed 's/^/   - /'
echo ""

# Step 4: Commit
echo "💾 COMMITTING..."
git commit -m "$COMMIT_MSG" || {
  echo "❌ Commit failed (might be no changes staged)"
  exit 1
}
COMMIT_HASH=$(git rev-parse --short HEAD)
echo "   ✓ Committed as $COMMIT_HASH"
echo ""

# Step 5: Run deploy script
echo "🚀 RUNNING DEPLOYMENT..."
echo "   Target instances: All (push to GitHub, pull to others)"
echo ""

DEPLOY_OUTPUT=$("$SCRIPT_DIR/deploy.sh" 2>&1) || {
  echo "❌ Deployment failed"
  echo ""
  echo "Raw output:"
  echo "$DEPLOY_OUTPUT"
  exit 1
}

echo "$DEPLOY_OUTPUT" | python3 -m json.tool 2>/dev/null || echo "$DEPLOY_OUTPUT"
echo ""

# Step 6: Parse results and show summary
echo "📊 DEPLOYMENT SUMMARY:"
echo "---"

SERVICES_RESTART=$(echo "$DEPLOY_OUTPUT" | python3 -c "import sys, json; d = json.load(sys.stdin); print(d.get('services_need_restart', 'false'))" 2>/dev/null || echo "false")
RESTART_REASON=$(echo "$DEPLOY_OUTPUT" | python3 -c "import sys, json; d = json.load(sys.stdin); print(d.get('restart_reason', ''))" 2>/dev/null || echo "")
FILES_CHANGED=$(echo "$DEPLOY_OUTPUT" | python3 -c "import sys, json; d = json.load(sys.stdin); print(d.get('files_changed', 0))" 2>/dev/null || echo "0")
INSTANCES=$(echo "$DEPLOY_OUTPUT" | python3 -c "import sys, json; d = json.load(sys.stdin); print(', '.join(d.get('other_instances_updated', [])))" 2>/dev/null || echo "unknown")

echo "✓ Files changed: $FILES_CHANGED"
echo "✓ Instances updated: $INSTANCES"

if [ "$SERVICES_RESTART" = "true" ]; then
  echo ""
  echo "⚠️  SERVICE RESTART NEEDED: $RESTART_REASON"
  echo ""
  echo "Would you like to restart services now? (y/n)"
  read -t 10 -p "Restart: " RESTART_RESPONSE || RESTART_RESPONSE="n"

  if [[ "$RESTART_RESPONSE" =~ ^[Yy] ]]; then
    echo "🔄 Restarting services..."
    # Detect and restart based on instance
    case "$INSTANCE_NAME" in
      "instance2-claude-bridge")
        cd /root/claude-code-bridge
        if [ -f "start.sh" ]; then
          bash start.sh &
          echo "   ✓ Instance 2 restart initiated"
        fi
        ;;
      "instance3-claude-bridge-standalone")
        cd /var/www/html/claude-code-bridge-standalone
        if [ -f "start.sh" ]; then
          bash start.sh &
          echo "   ✓ Instance 3 restart initiated"
        fi
        ;;
      "instance6-castle-data")
        ssh -i ~/.ssh/id_rsa_PBC root@64.23.255.113 \
          "docker restart castle-app" && \
          echo "   ✓ Castle-data container restarted" || \
          echo "   ❌ Failed to restart castle-data"
        ;;
    esac
  else
    echo "⏭️  Skipping restart. Remember to restart manually when ready."
  fi
else
  echo "✓ No service restart needed"
fi

echo ""
echo "=========================================="
echo "✅ DEPLOYMENT COMPLETE"
echo "=========================================="
